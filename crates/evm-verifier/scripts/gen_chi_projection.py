"""Compile native packed Keccak projection and embedding into shared XOR circuits."""

from collections import Counter
from itertools import combinations
from pathlib import Path
import re


def masks(source, name):
    matrix = re.search(rf"const {name}: \[u\d+; 16\] = \[(.*?)\];", source, re.S)
    values = [int(value, 16) for value in re.findall(r"0x[0-9a-f]+", matrix.group(1))]
    assert len(values) == 16
    return values


def term(index):
    return f"c[{index}]" if index < 47 else f"common{index - 47}"


def xor_circuit(name, masks):
    rows = [{i for i in range(47) if mask & (1 << i)} for mask in masks]
    forms = [1 << i for i in range(47)]
    lines = [f"    function {name}(uint192[47] memory c) internal pure returns (uint192[{len(rows)}] memory lanes) {{"]
    while True:
        counts = Counter(pair for row in rows for pair in combinations(sorted(row), 2))
        if not counts or max(counts.values()) < 2:
            break
        left, right = max(sorted(counts), key=counts.get)
        index = len(forms)
        forms.append(forms[left] ^ forms[right])
        for row in rows:
            if left in row and right in row:
                row.difference_update([left, right])
                row.add(index)
        lines.append(f"        uint192 {term(index)} = {term(left)} ^ {term(right)};")
    for lane, (mask, row) in enumerate(zip(masks, rows, strict=True)):
        actual = 0
        for i in row:
            actual ^= forms[i]
        assert actual == mask
        expression = " ^ ".join(term(i) for i in sorted(row)) or "0"
        assignment = f"        lanes[{lane}] ="
        separator = " " if len(assignment) + len(expression) + 2 <= 120 else "\n            "
        lines.append(f"{assignment}{separator}{expression};")
    return "\n".join([*lines, "    }"])


crate = Path(__file__).resolve().parents[1]
source = (crate.parent / "flock-backend/src/checkpoint_keccak/packed/maps.rs").read_text()
project, embed = masks(source, "PROJECT"), masks(source, "EMBED")
assert max(project).bit_length() == 47 and max(embed).bit_length() == 24
# Coefficient b of the embedding polynomial is the XOR of the projected
# lanes whose fixed embedding contains t^b. Compose both binary maps once.
combined = [0] * 24
for projection_row, embedding in zip(project, embed, strict=True):
    for bit in range(24):
        if embedding & (1 << bit):
            combined[bit] ^= projection_row

out = crate / "contracts/imt/NativeChiMap.sol"
out.write_text("""// SPDX-License-Identifier: MIT
pragma solidity ^0.8.28;

// Generated by scripts/gen_chi_projection.py from the native PROJECT and EMBED matrices.
// Matrices from leanEthereum/leanVM, copyright (c) 2026 leanEthereum.
library NativeChiMap {
""" + xor_circuit("project", project) + "\n\n" + xor_circuit("embedded", combined) + "\n}\n")
