"""Emit the static WHIR parameters from a trusted, Rust-verified midpoint trace."""

import argparse
import json
from pathlib import Path


def render(doc):
    strong = "experimental-binary-checkpoint-terminal64-shared-fold4-midpoint-v1"
    comparison = "experimental-binary-checkpoint-terminal64-shared-fold4-midpoint-comparison-v1"
    if doc["protocol"] not in (strong, comparison):
        raise ValueError("expected a trusted midpoint profile")
    first = doc["shared_bit_batch"]["ring_switch"]["initial_fold"]
    tail = first["tail"]
    steps = tail["steps"]
    if len(steps) != 4 or len(tail["final_fold"]["point"]) != 4:
        raise ValueError("unsupported WHIR geometry")
    # Each quadratic domain ends with a 32-byte shape identity and 16 bytes of framing.
    domains = [bytes.fromhex(s["fold"]["domain"]) for s in steps] + [bytes.fromhex(tail["final_fold"]["domain"])]
    prefix, suffix = domains[0][:-48], domains[0][-16:]
    if any(d[:-48] != prefix or d[-16:] != suffix for d in domains):
        raise ValueError("incompatible quadratic sumcheck domain encoding")
    oods = [len(first["round_answers"])] + [ (len(s["next_message"]) // 2 - 32) // 24 for s in steps[:-1]]
    if len(first["ood_answers"]) not in (1, 2) or any(n != len(first["ood_answers"]) for n in oods):
        raise ValueError("unsupported OOD shape")
    numbers = {
        "FIRST_COUNT": len(first["query_indices"]), "INITIAL_OODS": len(first["ood_answers"]),
        "FIRST_QUERY_BITS": first["query_pow_bits"], "INITIAL_FOLD_BITS": first["pow_bits"],
    }
    words = {
        "ROUND_COUNTS": bytes(len(s["indices"]) for s in steps),
        "ROUND_QUERY_BITS": bytes(s["query_bits"] for s in steps),
        "ROUND_FOLD_BITS": bytes(s["fold"]["pow_bits"] for s in steps),
    }
    domains_hex = {"WHIR_DOMAIN": first["whir_domain"], "BATCHING_DOMAIN": first["batching_domain"],
                   "INITIAL_DOMAIN": first["sumcheck_domain"],
                   "FOLD_IDS": b"".join(d[-48:-16] for d in domains).hex()}
    lines = ["// SPDX-License-Identifier: MIT", "pragma solidity ^0.8.28;", "",
             "// Generated by scripts/midpoint_policy.py from the native " + doc["protocol"] + " schedule.",
             "library NativeMidpointPolicy {"]
    lines.extend(f"    uint256 internal constant {name} = {value};" for name, value in numbers.items())
    lines.extend(f'    bytes4 internal constant {name} = hex"{value.hex()}";' for name, value in words.items())
    for name, value in domains_hex.items():
        lines.extend([f"    bytes internal constant {name} =", f'        hex"{value}";'])
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("trace", type=Path)
    args = parser.parse_args()
    print(render(json.loads(args.trace.read_bytes())), end="")
