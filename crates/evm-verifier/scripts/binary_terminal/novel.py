"""Generate the linear maps of the normalized additive subspace polynomials on the query domain."""

MASK = (1 << 64) - 1


def mul(a, b):
    acc = 0
    while b:
        if b & 1:
            acc ^= a
        a = ((a << 1) & MASK) ^ (0x1B if a >> 63 else 0)
        b >>= 1
    return acc


def inverse(x):
    out = 1
    exponent = MASK - 1
    while exponent:
        if exponent & 1:
            out = mul(out, x)
        x = mul(x, x)
        exponent >>= 1
    return out


def columns():
    basis = [1 << i for i in range(25)]
    normalized = []
    for k in range(21):
        root = basis[k]
        inv = inverse(root)
        assert mul(root, inv) == 1
        normalized.append([mul(v, inv) for v in basis])
        basis = [mul(v, v) ^ mul(root, v) for v in basis]
    # Each word covers one input bit and four output coordinates. It contains
    # four output field elements. All blocks below the diagonal vanish.
    out = bytearray()
    for group in range(6):
        for nib in range(group, 7):
            for bit in range(4):
                packed = 0
                for lane in range(4):
                    i, j = 4 * group + lane, 4 * nib + bit
                    if i < 21 and j < 25:
                        packed |= normalized[i][j] << (64 * lane)
                out.extend(packed.to_bytes(32, "big"))
    return out


